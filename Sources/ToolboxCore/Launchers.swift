import Foundation

/// Shell launchers such as `pyide .`, written to `~/.local/bin`.
public struct Launchers: Sendable {
    public let directory: URL
    static let marker = "# Generated by IDE Toolbox"

    public init(directory: URL = Launchers.defaultDirectory) { self.directory = directory }

    public static var defaultDirectory: URL {
        FileManager.default.homeDirectoryForCurrentUser.appendingPathComponent(".local/bin")
    }

    public func url(for tool: Tool) -> URL { directory.appendingPathComponent(tool.cliName) }

    public static func script(for tool: Tool, app: URL) -> String {
        let appPath = app.path.replacingOccurrences(of: "\"", with: "\\\"")
        guard tool.acceptsFolderArgument else {
            return """
            #!/bin/sh
            \(marker)
            exec open -a "\(appPath)"

            """
        }
        // A new instance per folder, since each IDE window is one project.
        return """
        #!/bin/sh
        \(marker)
        APP="\(appPath)"
        [ $# -eq 0 ] && exec open -a "$APP"
        case "$1" in
          /*) target="$1" ;;
          *)  target="$PWD/$1" ;;
        esac
        exec open -n -a "$APP" --args "$target" \(Catalog.folderLaunchArguments.joined(separator: " "))

        """
    }

    /// Writes (or refreshes) the launcher. Refuses to overwrite a file the Toolbox didn't create.
    public func install(_ tool: Tool, app: URL) throws {
        let url = url(for: tool)
        if let existing = try? String(contentsOf: url, encoding: .utf8), !existing.contains(Self.marker) {
            throw CocoaError(.fileWriteFileExists, userInfo: [NSFilePathErrorKey: url.path])
        }
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        try Self.script(for: tool, app: app).write(to: url, atomically: true, encoding: .utf8)
        try FileManager.default.setAttributes([.posixPermissions: 0o755], ofItemAtPath: url.path)
    }

    public func remove(_ tool: Tool) {
        let url = url(for: tool)
        guard let existing = try? String(contentsOf: url, encoding: .utf8), existing.contains(Self.marker) else { return }
        try? FileManager.default.removeItem(at: url)
    }

    public func isInstalled(_ tool: Tool) -> Bool {
        (try? String(contentsOf: url(for: tool), encoding: .utf8))?.contains(Self.marker) ?? false
    }
}
